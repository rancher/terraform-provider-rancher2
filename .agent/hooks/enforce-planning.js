#!/usr/bin/env node
//
// Runs as a PreToolUse (Claude Code) / BeforeTool (Gemini) hook. Both hosts send the
// same stdin shape (tool_name, tool_input, cwd) but use different tool-name vocabularies
// and different decision fields, so allow()/deny() below emit a JSON object that satisfies
// both: top-level decision/reason (Gemini) plus hookSpecificOutput.permissionDecision
// (Claude Code). Each host reads only the fields it recognizes and ignores the rest.
import { execSync } from 'child_process';
import fs from 'fs';
import path from 'path';

// Claude Code's file-write tools vs Gemini's
const WRITE_TOOL_NAMES = new Set(['write_file', 'replace', 'Write', 'Edit', 'MultiEdit']);

function allow() {
  console.log(JSON.stringify({ decision: "allow" }));
  process.exit(0);
}

function deny(reason, systemMessage) {
  console.log(JSON.stringify({
    decision: "deny",
    reason,
    systemMessage,
    hookSpecificOutput: {
      hookEventName: "PreToolUse",
      permissionDecision: "deny",
      permissionDecisionReason: reason
    }
  }));
  process.exit(0);
}

function main() {
  let inputData;
  try {
    inputData = JSON.parse(fs.readFileSync(0, 'utf-8'));
  } catch (err) {
    console.error("Failed to parse stdin JSON:", err);
    allow();
  }

  const { tool_name, tool_input, cwd } = inputData;

  // We only inspect file-write tool calls
  if (!WRITE_TOOL_NAMES.has(tool_name)) {
    allow();
  }

  const filePath = tool_input.file_path;
  if (!filePath) {
    allow();
  }

  // Anti-Bypass Guardrail: Unconditionally deny any manual writing, editing, or spoofing of review-approval.json
  if (filePath.endsWith('review-approval.json')) {
    deny(
      "Security Policy Violation: Manually writing, editing, or spoofing the proactive review approval file is strictly prohibited.\n\n" +
      "The approval file must ONLY be generated by delegating a real proactive review to our custom @review_agent subagent.\n\n" +
      "To proceed:\n" +
      "1. In the chat, invoke the review agent: @review_agent Please review my current staged changes.\n" +
      "2. The review agent will run static checks, analyze the diff, and programmatically write the secure approval file with correct checksums.\n" +
      "3. Never attempt to manually create, edit, or spoof the review-approval.json file.",
      "🔒 Security Block: Direct modification of review-approval.json is prohibited."
    );
  }

  // Resolve absolute path to check if it's within .agent/, .gemini/, or .claude/
  const resolvedPath = path.resolve(cwd || process.cwd(), filePath);
  const relativePath = path.relative(cwd || process.cwd(), resolvedPath);
  const relativePathNormalized = relativePath.replace(/\\/g, '/');

  // If the file is inside the .agent, .gemini, or .claude directories, we always allow.
  if (
    relativePathNormalized.startsWith('.agent/') ||
    relativePathNormalized.startsWith('.gemini/') ||
    relativePathNormalized.startsWith('.claude/') ||
    relativePathNormalized === 'AGENTS.md' ||
    relativePathNormalized === 'GEMINI.md'
  ) {
    allow();
  }

  // Check if there is an active/modified plan in git status
  try {
    const statusOutput = execSync('git status --porcelain', {
      cwd: cwd || process.cwd(),
      stdio: ['ignore', 'pipe', 'ignore']
    }).toString();

    // Check if git status has any modified (M), added (A), or untracked (??) plan files in .agent/plans/
    const hasActivePlan = statusOutput.split('\n').some(line => {
      const trimmed = line.trim();
      if (!trimmed.includes('.agent/plans/')) return false;
      const status = line.substring(0, 2);
      // Ensure the file is not deleted ('D') or ignored ('!')
      return !status.includes('D') && !status.includes('!');
    });

    if (!hasActivePlan) {
      deny(
        "Security Policy Violation: Modifying source code is strictly prohibited without an active plan.\n\n" +
        "In accordance with Phase 2, Steps 4-5 (Planning, Strategy & Blueprint Synchronization) of 'development-process.md', you MUST first create or update a unified plan in '.agent/plans/' before applying edits to source files.\n\n" +
        "To proceed:\n" +
        "1. Create or update a unified plan (e.g. '.agent/plans/MyTask.md') containing a high-level abstract (top half) and a step-by-step '## Implementation Checklist' (bottom half) as detailed in Phase 2, Step 4.\n" +
        "2. Present the plan in chat and obtain explicit developer approval to execute it (Phase 2, Step 5).\n" +
        "3. Once the plan file is created and visible in 'git status', you will be authorized to modify source files.",
        "🔒 Security Block: No active plan found. Please comply with Phase 2, Steps 4-5 of development-process.md."
      );
    }
  } catch (err) {
    console.error("Failed to run git status:", err);
    deny(
      "Security Policy Violation: Failed to verify active plan status in Git. Please ensure Git is configured and running properly.",
      "🔒 Security Block: Git command execution failed."
    );
  }

  allow();
}

main();
