#!/usr/bin/env node
//
// Runs as a PreToolUse (Claude Code) / BeforeTool (Gemini) hook. Both hosts send the
// same stdin shape (tool_name, tool_input, cwd) but use different tool-name vocabularies
// and different decision fields, so allow()/deny() below emit a JSON object that satisfies
// both: top-level decision/reason (Gemini) plus hookSpecificOutput.permissionDecision
// (Claude Code). Each host reads only the fields it recognizes and ignores the rest.
import { execSync, execFileSync } from 'child_process';
import fs from 'fs';
import path from 'path';

// Claude Code's shell tool vs Gemini's
const SHELL_TOOL_NAMES = new Set(['run_shell_command', 'Bash']);

function allow() {
  console.log(JSON.stringify({ decision: "allow" }));
  process.exit(0);
}

function deny(reason, systemMessage) {
  console.log(JSON.stringify({
    decision: "deny",
    reason,
    systemMessage,
    hookSpecificOutput: {
      hookEventName: "PreToolUse",
      permissionDecision: "deny",
      permissionDecisionReason: reason
    }
  }));
  process.exit(0);
}

function main() {
  let inputData;
  try {
    inputData = JSON.parse(fs.readFileSync(0, 'utf-8'));
  } catch (err) {
    console.error("Failed to parse stdin JSON:", err);
    allow();
  }

  const { tool_name, tool_input, cwd } = inputData;

  // We only inspect shell-command tool calls
  if (!SHELL_TOOL_NAMES.has(tool_name) || !tool_input || !tool_input.command) {
    allow();
  }

  const command = tool_input.command.trim();

  // Strip leading env var assignments (e.g. KEY=value or KEY="value" or KEY='value') and optional sudo
  let commandClean = command;
  while (true) {
    const next = commandClean.replace(/^[A-Za-z_][A-Za-z0-9_]*=(?:'[^']*'|"[^"]*"|\S+)\s+/, '');
    if (next === commandClean) break;
    commandClean = next;
  }

  // Anti-Bypass Guardrail: Unconditionally deny any manual writing, editing, or spoofing of review-approval.json
  const isManipulatingApproval = /\b(echo|cat|touch|rm|mv|cp|write|tee|vim|vi|nano|printf|sed|awk)\b.*\breview-approval\.json\b|>>?[^>]*\breview-approval\.json\b/.test(commandClean);
  if (isManipulatingApproval) {
    deny(
      "Security Policy Violation: Manually writing, editing, or spoofing the proactive review approval file is strictly prohibited.\n\n" +
      "The approval file must ONLY be generated by delegating a real proactive review to our custom @review_agent subagent.\n\n" +
      "To proceed:\n" +
      "1. In the chat, invoke the review agent: @review_agent Please review my current staged changes.\n" +
      "2. The review agent will run static checks, analyze the diff, and programmatically write the secure approval file with correct checksums.\n" +
      "3. Never attempt to manually create, edit, or spoof the review-approval.json file.",
      "🔒 Security Block: Direct manipulation of review-approval.json is prohibited."
    );
  }

  // Check if we are attempting to switch branches while current PR is in Draft mode (Phase 6, Step 18 / Phase 7, Step 20)
  let isBranchSwitch = false;
  if (/\bgit\s+switch\b/.test(commandClean)) {
    isBranchSwitch = true;
  } else if (/\bgit\s+checkout\b/.test(commandClean)) {
    // Check if it is a file-only checkout.
    // A file checkout is characterized by:
    // 1. It contains " -- " followed by a file path, e.g. "git checkout -- file.js".
    // 2. Or the arguments (excluding flags like -f, -q) correspond to existing files/folders on disk.
    const hasDoubleDash = commandClean.includes(' -- ');
    if (hasDoubleDash) {
      isBranchSwitch = false;
    } else {
      // Parse all non-flag arguments
      const parts = commandClean.split(/\s+/).filter(p => p !== 'git' && p !== 'checkout');
      const nonFlagParts = parts.filter(p => !p.startsWith('-') || p === '-'); // Keep '-' because "git checkout -" is a branch switch!
      
      if (nonFlagParts.length > 0) {
        const target = nonFlagParts[0];
        if (target === '-') {
          isBranchSwitch = true;
        } else {
          const resolvedTarget = path.resolve(cwd || process.cwd(), target);
          if (!fs.existsSync(resolvedTarget)) {
            isBranchSwitch = true;
          }
        }
      } else {
        // git checkout with no non-flag arguments (e.g. "git checkout" or "git checkout -f")
        // does not change the current branch, it just discards changes or prints status.
        isBranchSwitch = false;
      }
    }
  }

  if (isBranchSwitch) {
    try {
      const currentBranch = execSync('git branch --show-current', {
        cwd: cwd || process.cwd(),
        stdio: ['ignore', 'pipe', 'ignore']
      }).toString().trim();

      if (currentBranch && currentBranch !== 'main') {
        // Safe command invocation using execFileSync to completely eliminate shell interpolation / command injection risks
        let prStatusOutput;
        try {
          prStatusOutput = execFileSync('gh', ['pr', 'view', currentBranch, '--json', 'isDraft,number'], {
            cwd: cwd || process.cwd(),
            stdio: ['ignore', 'pipe', 'pipe'] // Capture stderr!
          }).toString().trim();
        } catch (execErr) {
          const stderr = execErr.stderr ? execErr.stderr.toString() : '';
          if (stderr.includes('no pull requests found')) {
            // No PR exists for this branch yet, which is perfectly fine!
            prStatusOutput = '';
          } else {
            throw execErr; // Re-throw other real failures to be caught by outer catch
          }
        }

        if (prStatusOutput) {
          const prInfo = JSON.parse(prStatusOutput);
          if (prInfo.isDraft === true) {
            deny(
              `Security Policy Violation: Moving to a new PR or branch is prohibited while the current branch PR (#${prInfo.number}) is still in Draft mode.\n\n` +
              `In accordance with Phase 6, Step 18 (Convert to Ready) and Phase 7, Step 20 (Proceed to Next Layer) of 'development-process.md', you MUST first graduate the current PR from Draft to Ready-for-Review before checking out 'main' or switching tasks.\n\n` +
              `To proceed:\n` +
              `1. Complete all iteration reviews and obtain local sign-off.\n` +
              `2. Convert the draft PR to Ready-for-Review (Phase 6, Step 18) using: \`gh pr ready ${prInfo.number}\` (or the create-pr.sh skill).\n` +
              `3. Once the PR is marked as ready for review on GitHub, you will be authorized to switch branches (Phase 7, Step 20).`,
              `🔒 Security Block: Current PR #${prInfo.number} is in Draft mode. Please comply with Phase 6, Step 18 of development-process.md.`
            );
          }
        }
      }
    } catch (err) {
      console.error("Failed to verify branch PR status:", err);
      deny(
        "Security Policy Violation: Failed to verify draft PR status on GitHub. To prevent branch state divergence, operations are blocked until status can be verified.",
        "🔒 Security Block: Branch PR verification failed."
      );
    }
  }

  // Check for unauthorized git commit or push operations
  const isCommitOrPush = /\bgit\s+(commit|push)\b/.test(commandClean);
  if (isCommitOrPush) {
    deny(
      `Security Policy Violation: Direct manual git commit and push commands are strictly prohibited in this repository.\n\n` +
      `In accordance with Phase 6, Step 15 (Authorized Commit & Push) of 'development-process.md', you MUST use our custom, secure, and synchronized commit-and-push skill to perform commits and pushes.\n\n` +
      `This skill automatically validates file count limits, verifies proactive code reviews, synchronizes with upstream main, pulls/fetches from your fork remote, and executes GPG/SSH cryptographically signed and signed-off commits.\n\n` +
      `To proceed:\n` +
      `1. Stage your changes cleanly: \`git add <files>...\`\n` +
      `2. Execute the commit-push skill in the chat: \`.agent/skills/commit-push.sh -m "your commit message"\`\n` +
      `3. Provide manual confirmation and allow the skill to execute fully.`,
      "🔒 Security Block: Direct git commit/push is blocked. Please run '.agent/skills/commit-push.sh -m \"...\"' to commit."
    );
  }

  // Check if it is a git command and performs a remote-interacting operation
  const isGitCmd = /^(?:sudo\s+)?git\b/.test(commandClean);
  const isRemoteOp = /\b(push|pull|fetch|clone|remote)\b/.test(commandClean);

  if (isGitCmd && isRemoteOp) {
    const targetDir = tool_input.dir_path || cwd || process.cwd();

    // Check command string directly to catch inline URL references or remote additions
    // Ignore false positives from the filename "block-rancher-git.js"
    const hasRancherRef = /rancher/i.test(command.replace(/block-rancher-git\.js/g, ''));
    if (hasRancherRef) {
      deny(
        "Security Policy Violation: Git command contains references to Rancher remote/URLs, which is strictly blocked.",
        "🔒 Security Block: Prohibited remote/URL reference detected."
      );
    }

    try {
      // Fetch remote URLs configured in this repo
      const remotesOutput = execSync('git remote -v', {
        cwd: path.resolve(targetDir),
        stdio: ['ignore', 'pipe', 'ignore']
      }).toString();

      // Check if any remote URL contains "rancher" (case-insensitive)
      if (/rancher/i.test(remotesOutput)) {
        deny(
          "Security Policy Violation: Operations (push, pull, fetch, remote) targeting Rancher-owned remotes are strictly blocked.",
          "🔒 Security Block: Git remote operation against a Rancher remote is prohibited."
        );
      }
    } catch (err) {
      console.error("Failed to check git remote safety:", err);
      deny(
        "Security Policy Violation: Failed to check git remote safety configuration.",
        "🔒 Security Block: Remote safety verification failed."
      );
    }
  }

  // Allow all other commands to proceed
  allow();
}

main();
